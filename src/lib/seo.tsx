import type { Metadata } from "next";
import {
  SITE_URL,
  ANDROID_PACKAGE,
  IOS_APP_ID,
  IOS_MIN_VERSION,
  brand,
  contact,
  founder,
  productLines,
} from "./site";
import { PLAN_RATE, planOrder, plans, fromRate, type Currency } from "./plans";

const SCHEMA_CURRENCIES: Currency[] = ["INR", "USD"];

/**
 * Stable node identifiers for the entity graph.
 *
 * Until 2026-11-16 every schema block declared its OWN anonymous
 * Organization: websiteSchema had a publisher, aboutPageSchema a mainEntity,
 * productSchema another publisher — each a fresh node carrying nothing but a
 * name. An engine reading the site therefore found four unlinked things
 * called "OZZO Technologies", and a SoftwareApplication with no stated maker,
 * rather than one company that publishes one product on one website.
 *
 * That is the condition under which an engine falls back on the NAME alone to
 * decide what a domain is — and this name is shared with a food-ordering
 * brand. On 2026-11-15 Google's AI Mode duly answered that OZZO is a Mumbai
 * pizza restaurant, with this company's real email address and phone number
 * printed underneath it.
 *
 * A URI @id fixes the shape: every block now POINTS AT the same node instead
 * of describing a new one, so the graph states that this website, this app,
 * this about page and this founder all belong to one identified company in
 * Rajkot. Anything else on the page may be re-described; the @id is what
 * makes them the same thing.
 */
export const ORG_ID = SITE_URL + "/#organization";
export const WEBSITE_ID = SITE_URL + "/#website";
export const SOFTWARE_ID = SITE_URL + "/#software";

/**
 * The social share card, stated explicitly.
 *
 * It is generated by the file convention at src/app/opengraph-image.tsx, but
 * that only covers a route whose metadata does not define `openGraph` itself.
 * Every page here DOES define it (for the canonical url and title), and a
 * child's `openGraph` replaces the parent's wholesale — which silently dropped
 * the image from all but the home page. The 2026-10-25 audit found og:image on
 * 1 of 66 pages, so every link shared on WhatsApp or LinkedIn rendered as bare
 * text. Setting it here means it cannot be lost again.
 */
export const OG_IMAGE = {
  url: `${SITE_URL}/opengraph-image`,
  width: 1200,
  height: 630,
  alt: `${brand.name} — ${brand.tagline}`,
};

/** Build per-page metadata with sensible OG/Twitter/canonical defaults. */
export function pageMetadata(opts: {
  title: string;
  description: string;
  path: string;
  keywords?: string[];
}): Metadata {
  const url = `${SITE_URL}${opts.path}`;
  return {
    title: opts.title,
    description: opts.description,
    keywords: opts.keywords,
    alternates: { canonical: url },
    openGraph: {
      type: "website",
      url,
      siteName: brand.name,
      title: opts.title,
      description: opts.description,
      images: [OG_IMAGE],
    },
    twitter: {
      card: "summary_large_image",
      title: opts.title,
      description: opts.description,
      images: [OG_IMAGE.url],
    },
  };
}

// City is the test, not street. We publish Rajkot, Gujarat without a street
// line, and keying this on `street` would silently drop the whole address
// from Organization schema — the exact gap that made Perplexity report the
// company as unverified.
const hasAddress = Boolean(contact.address.city);

/** Organization schema — identifies the business to search + AI engines. */
export function organizationSchema() {
  return {
    "@context": "https://schema.org",
    "@type": "Organization",
    "@id": ORG_ID,
    name: brand.legalName,
    alternateName: brand.name,
    url: SITE_URL,
    logo: `${SITE_URL}/brand/icon.png`,
    description: brand.description,
    /**
     * schema.org's purpose-built answer to "there is another company with
     * this name". It exists precisely to separate an item from similar ones,
     * and this is the case it was designed for.
     *
     * Written positive-first. What an engine can act on is the specific,
     * checkable claim — B2B software, sold by subscription, from a named city
     * — not the denial. The denial is one clause at the end, in category
     * words rather than naming the other brand: repeating a competitor's
     * product nouns across this domain would hand the association the very
     * co-occurrence it feeds on. The explicit, named version of this
     * disclaimer lives in /llms.txt, which is read by assistants and does not
     * compete for rankings.
     */
    disambiguatingDescription: `${brand.legalName} is a business-to-business software company based in ${contact.address.city}, ${contact.address.state}, India. It sells CRM and sales-force-automation software to companies on a per-user subscription. It is not a restaurant, a food brand or a food-delivery service, and it is not connected to any other business trading under the name "Ozzo".`,
    slogan: brand.tagline,
    /**
     * ISIC Rev.4 6201 — "Computer programming activities". The international
     * classification rather than NAICS, which is North American and would
     * imply a registration this company does not have. A machine-readable
     * industry code is a far harder signal than an adjective in a sentence.
     */
    isicV4: "6201",
    areaServed: { "@type": "Country", name: "India" },
    /**
     * What the company is an authority on. Mirrors the founder's knowsAbout
     * so the person and the company reinforce each other instead of each
     * floating free.
     */
    knowsAbout: [
      "Customer relationship management",
      "Sales force automation",
      "Field sales management",
      "Sales and distribution software",
      "Workforce automation",
      "Field force tracking",
      "Beat and route planning",
      "WhatsApp business messaging",
      "B2B SaaS",
    ],
    brand: {
      "@type": "Brand",
      name: brand.name,
      logo: `${SITE_URL}/brand/icon.png`,
    },
    email: contact.email,
    telephone: contact.phoneE164,
    ...(hasAddress
      ? {
          // Empty fields are omitted rather than emitted as "". A blank
          // streetAddress is not a neutral placeholder to a validator — it is
          // a declared-but-empty property, which reads worse than its absence.
          address: {
            "@type": "PostalAddress",
            ...(contact.address.street ? { streetAddress: contact.address.street } : {}),
            addressLocality: contact.address.city,
            addressRegion: contact.address.state,
            ...(contact.address.postalCode ? { postalCode: contact.address.postalCode } : {}),
            addressCountry: contact.address.country,
          },
        }
      : {}),
    contactPoint: {
      "@type": "ContactPoint",
      telephone: contact.phoneE164,
      email: contact.salesEmail,
      contactType: "sales",
      areaServed: "IN",
      availableLanguage: ["en", "hi"],
    },
    // A named human attached to the company is one of the strongest entity
    // signals there is — it is the difference between "a website" and "a
    // company someone runs".
    founder: { "@type": "Person", name: founder.name, jobTitle: founder.jobTitle },
    // Both store listings belong here too: a store page carrying the same
    // name, logo and developer is independent evidence that this company ships a
    // real product, and it is the one profile an engine can verify in a click.
    // Two stores under one developer name is a stronger signal than one — and
    // it is how an engine learns the app is not Android-only.
    sameAs: [
      ...Object.values(contact.social).filter(Boolean),
      brand.playStoreUrl,
      brand.appStoreUrl,
    ],
    /**
     * The product, named from the company side as well as the app side.
     * A one-way link is a claim; a two-way one is a relationship, and it is
     * what lets an engine answer "what does this company make" without
     * having to infer it from the marketing copy.
     */
    makesOffer: {
      "@type": "Offer",
      itemOffered: { "@id": SOFTWARE_ID },
    },
  };
}

/** Person schema for the founder — used on /about. */
export function founderSchema() {
  return {
    "@context": "https://schema.org",
    "@type": "Person",
    name: founder.name,
    jobTitle: founder.jobTitle,
    description: founder.bio,
    url: `${SITE_URL}/about`,
    worksFor: {
      "@type": "Organization",
      name: brand.legalName,
      url: SITE_URL,
    },
    knowsAbout: [
      "Sales force automation",
      "Customer relationship management",
      "Field sales",
      "Sales and distribution",
      "SaaS sales",
    ],
  };
}

/** AboutPage schema. */
export function aboutPageSchema() {
  return {
    "@context": "https://schema.org",
    "@type": "AboutPage",
    name: `About ${brand.legalName}`,
    url: `${SITE_URL}/about`,
    description: brand.metaDescription,
    // The page is about the identified company — the same node the home
    // page describes, not a fresh anonymous one with the same name.
    mainEntity: { "@id": ORG_ID },
  };
}

/** WebSite schema. */
export function websiteSchema() {
  return {
    "@context": "https://schema.org",
    "@type": "WebSite",
    "@id": WEBSITE_ID,
    name: brand.name,
    url: SITE_URL,
    description: brand.description,
    inLanguage: "en-IN",
    // The identified company, not a second one that happens to share a name.
    publisher: { "@id": ORG_ID },
  };
}

/** SoftwareApplication schema — each product line as an offering. */
export function softwareApplicationSchema() {
  return {
    "@context": "https://schema.org",
    "@type": "SoftwareApplication",
    "@id": SOFTWARE_ID,
    name: brand.name,
    applicationCategory: "BusinessApplication",
    // Who makes it. Without this the app is an orphan, and an orphan app
    // called OZZO is exactly what gets attached to the wrong OZZO.
    publisher: { "@id": ORG_ID },
    author: { "@id": ORG_ID },
    operatingSystem: brand.schemaOperatingSystem,
    description: brand.description,
    // With real store links an engine can answer "where do I get the app" with
    // the listings instead of pointing back at the marketing page. Both are
    // listed, so "is it on iPhone" is answerable from the markup alone.
    downloadUrl: [brand.playStoreUrl, brand.appStoreUrl],
    installUrl: [brand.playStoreUrl, brand.appStoreUrl],
    sameAs: [brand.playStoreUrl, brand.appStoreUrl],
    // An AggregateOffer with a real lowPrice is what lets Google and the AI
    // engines answer "how much is OZZO" with a number instead of "pricing is not
    // published". An Offer with priceCurrency and no price is ignored by both.
    // One AggregateOffer per currency, each carrying the real per-user rate for
    // every plan. A UnitPriceSpecification states the unit explicitly, so an
    // engine reads "100 INR per user per month" rather than a bare "100".
    offers: SCHEMA_CURRENCIES.map((currency) => ({
      "@type": "AggregateOffer",
      priceCurrency: currency,
      lowPrice: String(fromRate(currency)),
      highPrice: String(
        Math.max(...planOrder.map((id) => PLAN_RATE[currency][id])),
      ),
      offerCount: planOrder.length,
      availability: "https://schema.org/InStock",
      url: `${SITE_URL}/plans`,
      offers: planOrder.map((id) => {
        const plan = plans.find((p) => p.id === id);
        const price = String(PLAN_RATE[currency][id]);
        return {
          "@type": "Offer",
          name: `${brand.name} ${plan?.name ?? id}`,
          description: plan?.blurb,
          priceCurrency: currency,
          price,
          priceSpecification: {
            "@type": "UnitPriceSpecification",
            price,
            priceCurrency: currency,
            unitText: "user per month",
            billingDuration: 12,
          },
          availability: "https://schema.org/InStock",
          url: `${SITE_URL}/plans`,
        };
      }),
    })),
  };
}

/**
 * Per-product SoftwareApplication schema — describes a single product line
 * (CRM or SFA) as its own offering, so AI engines can distinguish
 * "OZZO CRM" from "OZZO SFA" as distinct products rather than only seeing
 * the whole platform. Use on the individual /products/[slug] pages.
 */
export function productSchema(slug: string) {
  const line = productLines.find((p) => p.slug === slug);
  if (!line) return softwareApplicationSchema();
  return {
    "@context": "https://schema.org",
    "@type": "SoftwareApplication",
    name: `${brand.name} ${line.name}`,
    alternateName: `${brand.name} ${line.fullName}`,
    applicationCategory: "BusinessApplication",
    operatingSystem: brand.schemaOperatingSystem,
    description: line.summary,
    // One app (OZZO SALES, on Android and iOS) serves both product lines, so
    // both point at the same two listings.
    downloadUrl: [brand.playStoreUrl, brand.appStoreUrl],
    installUrl: [brand.playStoreUrl, brand.appStoreUrl],
    url: `${SITE_URL}/products/${line.slug}`,
    featureList: line.features,
    publisher: { "@id": ORG_ID },
    isPartOf: { "@id": SOFTWARE_ID },
    offers: {
      "@type": "Offer",
      price: String(PLAN_RATE.INR[slug === "crm" ? "CRM" : "SFA"]),
      priceCurrency: "INR",
      priceSpecification: {
        "@type": "UnitPriceSpecification",
        price: String(PLAN_RATE.INR[slug === "crm" ? "CRM" : "SFA"]),
        priceCurrency: "INR",
        unitText: "user per month",
        billingDuration: 12,
      },
      availability: "https://schema.org/InStock",
      url: `${SITE_URL}/plans`,
    },
  };
}

/**
 * MobileApplication schema — one entry per store listing for the rep app.
 *
 * `softwareApplicationSchema()` above describes the whole OZZO platform, which
 * is mostly a web product. This describes the thing a rep installs on a phone,
 * and it exists because that is a different question with a different answer:
 * "is there an OZZO app for iPhone" is answered by an `iOS` MobileApplication
 * node with a real App Store `installUrl`, and by nothing else.
 *
 * Two nodes rather than one with `operatingSystem: "Android, iOS"`, because
 * each store listing has its own URL, its own id and its own OS requirement,
 * and an engine that wants to deep-link a user to the right store needs them
 * kept apart.
 */
export function mobileAppSchema() {
  const shared = {
    "@context": "https://schema.org",
    "@type": "MobileApplication",
    name: brand.mobileAppName,
    applicationCategory: "BusinessApplication",
    applicationSubCategory: "Field Sales / Sales Force Automation",
    description:
      `${brand.mobileAppName} is the OZZO field app for sales reps: selfie and GPS ` +
      "attendance, geo-tagged customer visits, beat routes, order capture, " +
      "payment collection and expenses — all of it working offline and syncing " +
      "when signal returns.",
    // The same identified company as everywhere else, not two more
    // anonymous nodes that merely share its name.
    publisher: { "@id": ORG_ID },
    author: { "@id": ORG_ID },
    isPartOf: { "@id": SOFTWARE_ID },
    // Free to install; the subscription is on the account, not the download.
    offers: {
      "@type": "Offer",
      price: "0",
      priceCurrency: "INR",
      availability: "https://schema.org/InStock",
    },
  };
  return [
    {
      ...shared,
      operatingSystem: "Android",
      downloadUrl: brand.playStoreUrl,
      installUrl: brand.playStoreUrl,
      url: brand.playStoreUrl,
      sameAs: brand.playStoreUrl,
      identifier: ANDROID_PACKAGE,
    },
    {
      ...shared,
      operatingSystem: `iOS ${IOS_MIN_VERSION}+`,
      downloadUrl: brand.appStoreUrl,
      installUrl: brand.appStoreUrl,
      url: brand.appStoreUrl,
      sameAs: brand.appStoreUrl,
      identifier: IOS_APP_ID,
      datePublished: brand.iosLaunchDate,
    },
  ];
}

/** FAQPage schema from a Q/A list. */
export function faqSchema(items: { q: string; a: string }[]) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: items.map((it) => ({
      "@type": "Question",
      name: it.q,
      acceptedAnswer: { "@type": "Answer", text: it.a },
    })),
  };
}

/**
 * BlogPosting schema for an individual article.
 *
 * `images` are the article's own illustrations, site-relative. Google asks for
 * them on an Article and uses them to decide what to show in search and in
 * Discover; an article with none is far less likely to be shown with a
 * picture at all. They are passed in rather than derived here so the schema
 * can never claim an image the page does not actually render.
 */
export function blogPostingSchema(
  post: {
    slug: string;
    title: string;
    description: string;
    date: string;
    author: string;
  },
  images: string[] = [],
) {
  const url = `${SITE_URL}/blog/${post.slug}`;
  return {
    "@context": "https://schema.org",
    "@type": "BlogPosting",
    headline: post.title,
    description: post.description,
    ...(images.length ? { image: images.map((src) => `${SITE_URL}${src}`) } : {}),
    datePublished: post.date,
    dateModified: post.date,
    author: { "@type": "Organization", name: post.author },
    publisher: {
      "@type": "Organization",
      name: brand.legalName,
      logo: { "@type": "ImageObject", url: `${SITE_URL}/brand/icon.png` },
    },
    mainEntityOfPage: { "@type": "WebPage", "@id": url },
    url,
  };
}

/** BreadcrumbList schema. */
export function breadcrumbSchema(crumbs: { name: string; path: string }[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: crumbs.map((c, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: c.name,
      item: `${SITE_URL}${c.path}`,
    })),
  };
}

/** Render a JSON-LD <script> tag. */
export function JsonLd({ data }: { data: object | object[] }) {
  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{ __html: JSON.stringify(data) }}
    />
  );
}
